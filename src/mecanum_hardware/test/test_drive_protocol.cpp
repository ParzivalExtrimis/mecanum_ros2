TEST(DriveProtocol, RejectsCorruptFrames)
{
  Bytes bad = kState;
  bad[20] ^= 0x01;  // a data byte: CRC fails
  EXPECT_FALSE(decode(bad).has_value());
  Bytes short_frame = {0x02, 0x30, 0x00};
  EXPECT_FALSE(decode(short_frame).has_value());
  // A CMD body with one byte missing: right CRC, wrong size.
  Bytes payload = {static_cast<std::uint8_t>(dp::MsgType::kCmd), 1, 0, 0};
  const std::uint16_t crc = dp::crc16(payload.data(), payload.size());
  payload.push_back(crc & 0xFF);
  payload.push_back(crc >> 8);
  Bytes frame = dp::cobs_encode(payload);
  EXPECT_FALSE(dp::decode_frame(frame.data(), frame.size()).has_value());
}

TEST(DriveProtocol, FrameReaderResyncsAfterGarbage)
{
  dp::FrameReader reader;
  Bytes stream = {0x13, 0x88, 0x42, 0x00};  // boot ROM noise, then a delimiter
  stream.insert(stream.end(), kState.begin(), kState.end());
  stream.insert(stream.end(), kHello.begin(), kHello.end());
  std::vector<dp::Message> out;
  // Fed in uneven pieces, as a serial port delivers them.
  for (std::size_t i = 0; i < stream.size(); i += 7) {
    const std::size_t n = std::min<std::size_t>(7, stream.size() - i);
    reader.feed(stream.data() + i, n, out);
  }
  ASSERT_EQ(out.size(), 2u);
  EXPECT_EQ(out[0].type, dp::MsgType::kState);
  EXPECT_EQ(out[1].type, dp::MsgType::kHello);
  EXPECT_EQ(reader.errors(), 1u);
}

TEST(DriveProtocol, RoundTripsState)
{
  dp::State s;
  s.seq = 65535;
  s.counts = {-1, 2, -3, 4};
  s.pulses = {5, -6, 7, -8};
  s.following_error = {9, -10, 11, -12};
  s.faults = dp::kFaultWatchdog;
  s.mode = dp::kModeIdle;
  const Bytes frame = dp::encode_state(s);
  const auto m = decode(frame);
  ASSERT_TRUE(m.has_value());
  EXPECT_EQ(m->state.counts, s.counts);
  EXPECT_EQ(m->state.pulses, s.pulses);
  EXPECT_EQ(m->state.following_error, s.following_error);
  EXPECT_EQ(m->state.seq, 65535);
}

