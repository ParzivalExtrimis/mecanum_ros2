TEST(DriveProtocol, CrcCheckValue)
{
  const char * text = "123456789";
  EXPECT_EQ(dp::crc16(reinterpret_cast<const std::uint8_t *>(text), 9), 0x29B1);
}

TEST(DriveProtocol, CobsRoundTripsRandomData)
{
  std::mt19937 rng(3);
  for (int trial = 0; trial < 500; ++trial) {
    Bytes data(rng() % 700);
    for (auto & b : data) {
      b = (rng() % 3 == 0) ? 0 : static_cast<std::uint8_t>(rng());
    }
    const Bytes encoded = dp::cobs_encode(data);
    for (const auto b : encoded) {
      ASSERT_NE(b, 0);
    }
    const auto decoded = dp::cobs_decode(encoded.data(), encoded.size());
    ASSERT_TRUE(decoded.has_value());
    EXPECT_EQ(*decoded, data);
  }
}

TEST(DriveProtocol, EncodesLikeTheReference)
{
  EXPECT_EQ(dp::encode_hello_req(), kHelloReq);

  dp::Hello hello{1, 0, 1, 4, 1600, 4000};
  EXPECT_EQ(dp::encode_hello(hello), kHello);

  dp::Config config;
  config.pulses_per_rev = 1600;
  config.counts_per_rev = 4000;
  config.motor_for_wheel = {2, 0, 3, 1};
  config.dir_invert = 0x05;
  config.enc_invert = 0x0a;
  config.watchdog_ms = 200;
  config.accel_backstop = 5.0f;
  config.max_wheel_speed = 3.0f;
  config.following_error_limit = 250;
  EXPECT_EQ(dp::encode_config(config), kConfig);

  EXPECT_EQ(dp::encode_config_ack(dp::ConfigAck{2}), kConfigAck);

  dp::Cmd cmd;
  cmd.seq = 513;
  cmd.flags = dp::kFlagEnable | dp::kFlagClearFault;
  cmd.wheel_velocity = {1.5f, -2.25f, 0.0f, 0.5f};
  EXPECT_EQ(dp::encode_cmd(cmd), kCmd);
}

